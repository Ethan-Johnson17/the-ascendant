import { validateCurriculum } from '../../engine/learning/curriculum.ts';
import { curriculumSql } from '../../services/curriculum/curriculumSql.ts';
import { findTemplate } from '../campaigns/catalog.ts';
import { historyEarlyCivilizations } from './historyEarlyCivilizations.ts';

/**
 * All authored curricula. SERVER-SIDE ONLY: these contain answer keys. Used by the content
 * migration generator and tests; never imported by the app's screens (enforced by a test).
 */
export const authoredCurricula = [historyEarlyCivilizations] as const;

export function authoredCurriculaSql(): { ok: true; sql: string } | { ok: false; issues: string[] } {
  const parts = ['-- The Ascendant — authored curricula (Phase 3). GENERATED by `npm run content:sql`; do not edit.\n'];
  const issues: string[] = [];
  for (const input of authoredCurricula) {
    const template = findTemplate(input.templateId);
    if (!template) {
      issues.push(`${input.templateId}: no campaign template`);
      continue;
    }
    const v = validateCurriculum(input, template.competencies.map((c) => c.key));
    if (!v.ok) issues.push(...v.issues.map((i) => `${input.templateId}: ${i}`));
    else {
      if (v.curriculum.version !== template.curriculumVersion) issues.push(`${input.templateId}: version ${v.curriculum.version} ≠ catalog curriculumVersion ${template.curriculumVersion}`);
      parts.push(curriculumSql(v.curriculum));
    }
  }
  return issues.length ? { ok: false, issues } : { ok: true, sql: parts.join('\n') };
}
