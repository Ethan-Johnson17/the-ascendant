import { listActivities, type Curriculum } from '../../engine/learning/curriculum.ts';

/**
 * Turns a validated curriculum into SQL that stores it (content tables in
 * supabase/migrations/*_learning_engine.sql). Used to generate authored-content migrations and to
 * load curricula into the offline test database. Ids are '<templateId>/<key>'.
 *
 * Only call this with the output of `validateCurriculum`: it assumes references are sound.
 */

const lit = (v: string | number | null | undefined): string =>
  v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;
const arr = (list: readonly string[]): string => (list.length ? `array[${list.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (v: unknown): string => `${lit(JSON.stringify(v))}::jsonb`;

/** insert … on conflict (key) do update: re-running a curriculum updates it and never deletes. */
function upsert(table: string, values: Record<string, string>, conflict = 'id'): string {
  const cols = Object.keys(values);
  const updates = cols.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`);
  return (
    `insert into public.${table} (${cols.join(', ')}) values (${cols.map((c) => values[c]).join(', ')})` +
    ` on conflict (${conflict}) do ${updates.length ? `update set ${updates.join(', ')}` : 'nothing'};`
  );
}

export function curriculumSql(c: Curriculum): string {
  const id = (key: string) => `${c.templateId}/${key}`;
  const ids = (keys: readonly string[]) => keys.map(id);
  const citations = (list: readonly { source: string; locator?: string | undefined }[]) =>
    list.map((ct) => ({ sourceId: id(ct.source), ...(ct.locator ? { locator: ct.locator } : {}) }));
  const out: string[] = [];
  const t = lit(c.templateId);

  out.push(`-- Curriculum ${c.templateId} v${c.version} (${c.origin}). Generated by src/services/curriculum/curriculumSql.ts — do not edit by hand.`);
  out.push(upsert('curricula', { template_id: t, version: lit(c.version), subject: lit(c.subject), origin: lit(c.origin) }, 'template_id'));
  out.push(`update public.campaign_templates set version = ${c.version} where id = ${t};`);

  for (const comp of c.competencies) {
    out.push(
      `update public.competency_definitions set description = ${lit(comp.description)}, prerequisite_ids = ${arr(ids(comp.prerequisites))} where id = ${lit(id(comp.key))};`,
    );
  }

  for (const s of c.sources) {
    out.push(
      upsert('sources', {
        id: lit(id(s.key)), template_id: t, key: lit(s.key), title: lit(s.title), author: lit(s.author), publisher: lit(s.publisher), url: lit(s.url),
        source_type: lit(s.sourceType), publication_date: lit(s.publicationDate), verification_status: lit(s.verification), checked_on: lit(s.checkedOn),
      }),
    );
  }

  const node = (key: string, parent: string | null, kind: string, title: string, summary: string, position: number) =>
    upsert('curriculum_nodes', {
      id: lit(id(key)), template_id: t, parent_id: parent === null ? 'null' : lit(id(parent)), kind: lit(kind), key: lit(key), title: lit(title), summary: lit(summary), position: lit(position),
    });
  c.disciplines.forEach((d, di) => {
    out.push(node(d.key, null, 'discipline', d.title, '', di));
    d.topics.forEach((tp, ti) => {
      out.push(node(tp.key, d.key, 'topic', tp.title, tp.summary, ti));
      tp.objectives.forEach((o, oi) => out.push(node(o.key, tp.key, 'objective', o.statement, '', oi)));
    });
  });

  // Codex entries before activities and questions, which refer to them.
  for (const e of c.codex) {
    out.push(
      upsert('codex_entries', {
        id: lit(id(e.key)), template_id: t, key: lit(e.key), title: lit(e.title), summary: lit(e.summary), explanation: arr(e.explanation),
        examples: arr(e.examples), applications: arr(e.applications), related_ids: arr(ids(e.related)), competency_ids: arr(ids(e.competencies)),
        certainty: lit(e.certainty), citations: json(citations(e.citations)),
      }),
    );
  }

  const positions = new Map<string, number>();
  for (const { objective, activity: a } of listActivities(c)) {
    const pos = positions.get(objective.key) ?? 0;
    positions.set(objective.key, pos + 1);
    const common = {
      id: lit(id(a.key)), template_id: t, objective_id: lit(id(objective.key)), key: lit(a.key), kind: lit(a.kind), title: lit(a.title),
      position: lit(pos), competency_ids: arr(ids(a.competencies)),
    };
    if (a.kind === 'lesson') {
      const sections = a.sections.map((s) => ({ ...s, citations: citations(s.citations) }));
      out.push(
        upsert('learning_activities', {
          ...common, estimated_minutes: lit(a.estimatedMinutes), sections: json(sections), introduces_ids: arr(ids(a.introduces)), target_stage: 'null', question_count: 'null', written_count: lit(0),
        }),
      );
    } else {
      out.push(upsert('learning_activities', { ...common, estimated_minutes: 'null', sections: 'null', introduces_ids: arr([]), target_stage: lit(a.targetStage), question_count: lit(a.questionCount), written_count: lit(a.writtenCount) }));
      a.items.forEach((item, ii) => {
        out.push(
          upsert('assessment_items', {
            id: lit(id(item.key)), activity_id: lit(id(a.key)), key: lit(item.key), concept_id: lit(id(item.concept)), kind: lit(item.kind),
            difficulty: lit(item.difficulty), position: lit(ii), definition: json(item),
          }),
        );
      });
    }
  }
  return out.join('\n') + '\n';
}
