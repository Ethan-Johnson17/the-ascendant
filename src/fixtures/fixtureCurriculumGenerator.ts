import type { CurriculumInput } from '../engine/learning/curriculum.ts';
import type { CurriculumGenerator, GenerationRequest } from '../services/curriculum/generator.ts';

/**
 * DEVELOPMENT FIXTURE — not AI, not real educational content.
 *
 * Produces a small, structurally complete curriculum for any subject name so the learning engine
 * can be exercised before the Phase 4 AI generator exists. Every curriculum it returns is marked
 * `origin: 'fixture'`, and its text says plainly that it is placeholder material. It must never be
 * presented to players as a real lesson.
 */

const slug = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'subject';

export function fixtureCurriculum(request: Pick<GenerationRequest, 'subject'>, templateId: string): CurriculumInput {
  const s = request.subject.trim();
  const note = `Placeholder text generated by the development fixture for "${s}". Not real course content.`;
  const item = (n: number, difficulty: 1 | 2 | 3) => ({
    key: `q${n}`,
    concept: n % 2 ? 'core-idea' : 'key-term',
    difficulty,
    kind: 'single_choice' as const,
    prompt: `Fixture question ${n} about ${s}. Choose option A.`,
    explanation: note,
    options: [
      { key: 'a', text: 'Option A (correct in this fixture)' },
      { key: 'b', text: 'Option B', errorCategory: 'related_concept_confusion' as const },
      { key: 'c', text: 'Option C' },
    ],
    answer: 'a',
  });
  return {
    templateId,
    version: 1,
    subject: s,
    origin: 'fixture',
    competencies: [
      { key: 'foundations', name: `${s} foundations`, attribute: 'int' },
      { key: 'application', name: `Applying ${s}`, attribute: 'wis', prerequisites: ['foundations'] },
    ],
    disciplines: [
      {
        key: slug(s),
        title: s,
        topics: [
          {
            key: 'introduction',
            title: `Introduction to ${s}`,
            summary: note,
            objectives: [
              {
                key: 'describe-core-idea',
                statement: `Describe the core idea of ${s}.`,
                activities: [
                  {
                    key: 'intro-lesson',
                    kind: 'lesson',
                    title: `What is ${s}?`,
                    competencies: ['foundations'],
                    estimatedMinutes: 5,
                    introduces: ['core-idea', 'key-term'],
                    sections: [{ paragraphs: [note], certainty: 'uncertain', citations: [{ source: 'fixture-source' }] }],
                  },
                  {
                    key: 'intro-check',
                    kind: 'assessment',
                    title: `${s}: first check`,
                    competencies: ['foundations'],
                    targetStage: 2,
                    questionCount: 3,
                    items: [item(1, 1), item(2, 1), item(3, 2), item(4, 2), item(5, 3), item(6, 3)],
                  },
                  {
                    key: 'apply-check',
                    kind: 'assessment',
                    title: `${s}: applying it`,
                    competencies: ['foundations', 'application'],
                    targetStage: 3,
                    questionCount: 2,
                    items: [item(7, 2), item(8, 2), item(9, 3)],
                  },
                ],
              },
            ],
          },
        ],
      },
    ],
    codex: [
      { key: 'core-idea', title: `Core idea of ${s}`, summary: note, explanation: [note], competencies: ['foundations'], certainty: 'uncertain', citations: [{ source: 'fixture-source' }] },
      { key: 'key-term', title: `A key term in ${s}`, summary: note, explanation: [note], competencies: ['foundations'], certainty: 'uncertain', related: ['core-idea'], citations: [{ source: 'fixture-source' }] },
    ],
    sources: [
      { key: 'fixture-source', title: 'Development fixture (not a real source)', publisher: 'The Ascendant development fixtures', sourceType: 'organization', verification: 'unverified' },
    ],
  };
}

export const fixtureCurriculumGenerator: CurriculumGenerator = {
  id: 'fixture',
  propose: async (request, templateId) => fixtureCurriculum(request, templateId),
};
