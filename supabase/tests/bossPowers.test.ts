import { before, describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { createCharacterAs, createTestDb, serviceStore, type TestDb } from './testDb.ts';
import { validateCurriculum, type CurriculumInput } from '../../src/engine/learning/curriculum.ts';
import { curriculumSql } from '../../src/services/curriculum/curriculumSql.ts';
import { createLearningService } from '../../src/services/learning/learningService.ts';
import { fixtureCurriculum } from '../../src/fixtures/fixtureCurriculumGenerator.ts';

/**
 * Race traits and class abilities in boss battles, against the real migrations. The course has two
 * skills with Apprentice checks, so the boss tests both and has spare questions for Lucky and
 * Adaptable. Option "a" is always right and "b" always wrong.
 */

const TEMPLATE = 'fixture-powers';
const FOUND = `${TEMPLATE}/foundations`;
const APPLY = `${TEMPLATE}/application`;
let t: TestDb;
type Body = Record<string, any>;

function course(): CurriculumInput {
  const c = structuredClone(fixtureCurriculum({ subject: 'Geology' }, TEMPLATE)) as any;
  const note = 'Placeholder text generated by the development fixture. Not real course content.';
  const item = (n: number, difficulty: 1 | 2) => ({
    key: `p${n}`, concept: 'applied-idea', difficulty, kind: 'single_choice', prompt: `Applied question ${n}. Choose option A.`, explanation: note,
    options: [{ key: 'a', text: 'Option A' }, { key: 'b', text: 'Option B' }, { key: 'c', text: 'Option C' }], answer: 'a',
  });
  c.disciplines[0].topics[0].objectives[0].activities[0].introduces.push('applied-idea');
  c.disciplines[0].topics[0].objectives[0].activities.push({
    key: 'apply-basics', kind: 'assessment', title: 'Geology: applied basics', competencies: ['application'], targetStage: 2, questionCount: 3,
    items: [item(1, 1), item(2, 1), item(3, 2), item(4, 2)],
  });
  c.codex.push({ key: 'applied-idea', title: 'An applied idea', summary: note, explanation: [note], competencies: ['application'], certainty: 'uncertain', citations: [{ source: 'fixture-source' }] });
  return c as CurriculumInput;
}

before(async () => {
  t = await createTestDb();
  const v = validateCurriculum(course(), ['foundations', 'application']);
  assert.ok(v.ok, JSON.stringify(!v.ok && v.issues));
  await t.db.exec(`
    insert into public.campaign_templates (id, subject, title, module, version) values ('${TEMPLATE}', 'Geology', 'Fixture: Geology', 'Fixture', 0);
    insert into public.campaign_sub_skills (template_id, attribute, name)
      select '${TEMPLATE}', a, 'Fixture ' || a from unnest(array['str','dex','con','int','wis','cha']) a;
    insert into public.competency_definitions (id, template_id, key, name, attribute) values
      ('${FOUND}', '${TEMPLATE}', 'foundations', 'Foundations', 'int'),
      ('${APPLY}', '${TEMPLATE}', 'application', 'Application', 'wis');
  `);
  await t.db.exec(curriculumSql(v.curriculum));
});

const svc = () => createLearningService(serviceStore(t));

/** A player whose two skills are at Apprentice, in a fresh campaign, with a battle started. */
async function battle(race: string, cls: string) {
  const u = await t.createUser();
  await createCharacterAs(t, u, 'Enheduanna', 'scholar', race, cls);
  const campaignId = await t.asUser(u, async (tx) => (await tx.query<{ id: string }>(`insert into public.campaigns (template_id) values ($1) returning id`, [TEMPLATE])).rows[0]!.id);
  for (const c of [FOUND, APPLY]) {
    await t.db.query(
      `insert into public.competency_progress (campaign_id, competency_id, user_id, mastery_stage) values ($1, $2, $3, 2)
       on conflict (campaign_id, competency_id) do update set mastery_stage = 2`, [campaignId, c, u]);
  }
  const start = await svc().handle(u, { action: 'start_boss', campaignId, stage: 2 });
  assert.equal(start.status, 200, JSON.stringify(start.body));
  let state = start.body as Body;
  const answer = async (a: string) => {
    const r = await svc().handle(u, { action: 'answer_boss', encounterId: state.encounter.id, position: state.encounter.position, answer: a });
    assert.equal(r.status, 200, JSON.stringify(r.body));
    state = r.body as Body;
    return state;
  };
  const use = async (power: string) => {
    const r = await svc().handle(u, { action: 'use_boss_power', encounterId: state.encounter.id, position: state.encounter.position, power });
    if (r.status === 200) state = r.body as Body;
    return r;
  };
  const ids = async () => (await t.db.query<{ question_ids: string[] }>(`select question_ids from public.boss_encounters where id = $1`, [state.encounter.id])).rows[0]!.question_ids;
  return { u, campaignId, get state() { return state; }, answer, use, ids };
}

const conceptOf = async (itemId: string) => (await t.db.query<{ concept_id: string }>(`select concept_id from public.assessment_items where id = $1`, [itemId])).rows[0]!.concept_id;
const competenciesOf = async (itemId: string) =>
  (await t.db.query<{ competency_ids: string[] }>(`select ce.competency_ids from public.assessment_items i join public.codex_entries ce on ce.id = i.concept_id where i.id = $1`, [itemId])).rows[0]!.competency_ids;

describe('Automatic powers', () => {
  it('Dwarf (Stalwart) starts with 4 Resolve; others with 3', async () => {
    assert.equal((await battle('dwarf', 'ranger')).state.encounter.maxResolve, 4);
    assert.equal((await battle('elf', 'ranger')).state.encounter.resolve, 3);
  });

  it('Cleric (Sanctuary): the first wrong answer costs nothing, the second costs 1', async () => {
    const b = await battle('elf', 'cleric');
    const first = await b.answer('b');
    assert.equal(first.encounter.resolve, 3);
    assert.equal(first.result.power, 'sanctuary');
    assert.equal(first.encounter.powers.find((p: Body) => p.id === 'sanctuary').used, true);
    const second = await b.answer('b');
    assert.equal(second.encounter.resolve, 2);
    assert.equal(second.result.power, null);
  });

  it('Fighter (Second Wind): the first correct answer after losing Resolve restores 1, once', async () => {
    const b = await battle('elf', 'fighter');
    assert.equal((await b.answer('a')).result.power, null, 'nothing to restore at full Resolve');
    await b.answer('b');
    const healed = await b.answer('a');
    assert.equal(healed.encounter.resolve, 3);
    assert.equal(healed.result.power, 'second_wind');
    await b.answer('b');
    assert.equal((await b.answer('a')).encounter.resolve, 2, 'only once per boss');
  });

  it('Halfling (Lucky): the first miss costs nothing and a new question on the same skill comes next', async () => {
    const b = await battle('halfling', 'ranger');
    const before = await b.ids();
    const missed = before[0]!;
    const r = await b.answer('b');
    assert.equal(r.result.power, 'lucky');
    assert.equal(r.encounter.resolve, 3);
    assert.equal(r.encounter.total, before.length + 1);
    const after = await b.ids();
    assert.deepEqual([after[0], ...after.slice(2)], before);
    assert.ok(!before.includes(after[1]!));
    assert.deepEqual(await competenciesOf(after[1]!), await competenciesOf(missed));
    const weak = (await t.db.query<{ n: number }>(`select count(*)::int as n from public.weakness_records where campaign_id = $1`, [b.campaignId])).rows[0]!.n;
    assert.equal(weak, 1, 'the miss still goes into the Weakness Bank');
  });
});

describe('Powers the player uses', () => {
  it('Human (Adaptable) swaps the current question for one on a different skill, once', async () => {
    const b = await battle('human', 'ranger');
    const before = await b.ids();
    const r = await b.use('adaptable');
    assert.equal(r.status, 200, JSON.stringify(r.body));
    const after = await b.ids();
    assert.deepEqual(after.slice(1), before.slice(1));
    assert.notDeepEqual(await competenciesOf(after[0]!), await competenciesOf(before[0]!));
    assert.equal(b.state.question.key, after[0]);
    assert.equal((await b.use('adaptable')).status, 409, 'once per boss');
  });

  it('Elf (Keen Insight) crosses out a wrong option, and the hint is still there when the battle resumes', async () => {
    const b = await battle('elf', 'ranger');
    const r = await b.use('keen_insight');
    assert.equal(r.status, 200);
    const hint = b.state.encounter.hint;
    assert.equal(hint.kind, 'remove_option');
    assert.notEqual(hint.optionKey, 'a');
    const resumed = await svc().handle(b.u, { action: 'view_boss', encounterId: b.state.encounter.id });
    assert.deepEqual((resumed.body as Body).encounter.hint, hint);
  });

  it('Rogue (Gambit) moves the current question to the end', async () => {
    const b = await battle('elf', 'rogue');
    const before = await b.ids();
    assert.equal((await b.use('gambit')).status, 200);
    assert.deepEqual(await b.ids(), [...before.slice(1), before[0]]);
  });

  it('Gambit can’t skip the last question', async () => {
    const b = await battle('elf', 'rogue');
    const n = (await b.ids()).length;
    for (let i = 0; i < n - 1; i++) await b.answer('a');
    assert.equal((await b.use('gambit')).status, 409);
  });

  it('Ranger (Scout Ahead) shows the next round’s skill and ideas', async () => {
    const b = await battle('elf', 'ranger');
    assert.equal((await b.use('scout_ahead')).status, 200);
    const scout = b.state.encounter.scout;
    assert.equal(scout.roundIndex, 1);
    assert.equal(scout.competencyName, b.state.encounter.plan.rounds[1].competencyName);
    assert.ok(scout.concepts.length >= 1);
  });

  it('Wizard (Arcane Recall) opens the Codex entry for the current question', async () => {
    const b = await battle('elf', 'wizard');
    assert.equal((await b.use('arcane_recall')).status, 200);
    assert.equal(b.state.encounter.recall.conceptId, await conceptOf(b.state.question.key));
  });

  it('a player can’t use a power that isn’t theirs', async () => {
    const b = await battle('elf', 'cleric');
    assert.equal((await b.use('gambit')).status, 403);
    assert.equal((await b.use('sanctuary')).status, 400, 'automatic powers can’t be used by hand');
  });
});

describe('The database checks every power', () => {
  it('refuses a power the player doesn’t have, a reused power, forged Resolve and forged question lists', async () => {
    const b = await battle('elf', 'ranger');
    const e = b.state.encounter;
    const ids = await b.ids();
    const record = (outcome: object) =>
      serviceStore(t).call('boss_record_answer', {
        p_user_id: b.u, p_encounter_id: e.id, p_position: 0,
        p_outcome: { itemId: ids[0], conceptId: 'x', correct: false, given: 'b', resolve: 3, status: 'active', xp: null, weakness: null, ...outcome },
      });
    await assert.rejects(record({ power: 'sanctuary' }), /not your power/);
    await assert.rejects(record({ power: 'second_wind', correct: true, resolve: 4 }), /not your power/);
    const usePower = (power: string, effect: object) =>
      serviceStore(t).call('boss_use_power', { p_user_id: b.u, p_encounter_id: e.id, p_position: 0, p_power: power, p_effect: effect });
    await assert.rejects(usePower('gambit', { questionIds: [...ids.slice(1), ids[0]] }), /not your power/);
    await usePower('keen_insight', { hint: { kind: 'remove_option', optionKey: 'b' } });
    await assert.rejects(usePower('keen_insight', { hint: {} }), /power already used/);

    const h = await battle('human', 'ranger');
    const hIds = await h.ids();
    await assert.rejects(
      serviceStore(t).call('boss_use_power', { p_user_id: h.u, p_encounter_id: h.state.encounter.id, p_position: 0, p_power: 'adaptable', p_effect: { questionIds: [hIds[1], hIds[0], ...hIds.slice(2)] } }),
      /question|not allowed/,
    );
  });

  it('refuses extra Resolve for anyone but a Dwarf', async () => {
    const b = await battle('elf', 'ranger');
    const q = await b.ids();
    await t.db.query(`delete from public.boss_encounters where id = $1`, [b.state.encounter.id]);
    await assert.rejects(
      serviceStore(t).call('boss_create_encounter', { p_user_id: b.u, p_campaign_id: b.campaignId, p_stage: 2, p_plan: {}, p_origin: 'game', p_question_ids: q, p_max_resolve: 4 }),
      /Resolve not allowed/,
    );
  });
});
